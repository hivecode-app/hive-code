"""Generate the typed bridge used by existing synchronous UI helpers from ARB.
New widgets use AppLocalizations directly. Run with --check to detect drift.
"""
import json,pathlib,re,sys
root=pathlib.Path(__file__).resolve().parents[1]
en=json.loads((root/'lib/l10n/app_en.arb').read_text())
calls=[]
for key in sorted((k for k in en if re.fullmatch(r'ui\d+',k)),key=lambda k:int(k[2:])):
 args=sorted(set(re.findall(r'{(p\d+)}',en[key])),key=lambda k:int(k[1:]))
 calls.append(f'      {key[2:]} => copy.{key}'+('('+', '.join('a['+str(i)+'].toString()' for i in range(len(args)))+')' if args else '')+',')
source='''// Generated by tool/generate_ui_copy.py from ARB; do not edit.
// New widgets use AppLocalizations. Existing synchronous UI helpers share the active
// catalogue, and their widgets subscribe to Localizations to rebuild on language changes.
import 'package:flutter/widgets.dart';
import 'app_localizations.dart';
import 'legacy_copy.dart';
class UiCopy {
  static AppLocalizations copy = lookupAppLocalizations(const Locale('en'));
  static bool legacy = true;
  static void configure(String language, bool newInterface) {
    legacy = !newInterface;
    copy = lookupAppLocalizations(Locale(language));
  }
  static void watch(BuildContext context) {
    final locale = Localizations.maybeLocaleOf(context);
    if (locale != null && locale.languageCode != copy.localeName) {
      copy = lookupAppLocalizations(Locale(locale.languageCode == 'he' ? 'he' : 'en'));
    }
  }
  static String text(int id, [List<Object?> a = const []]) {
    if (legacy) {
      var text = legacyCopy[id] ?? '';
      for (var i = 0; i < a.length; i++) { text = text.replaceAll('{p$i}', a[i].toString()); }
      return text;
    }
    return switch(id) {
'''+ '\n'.join(calls)+'''
      _ => throw ArgumentError.value(id, 'id'),
    };
  }
}
'''
target=root/'lib/l10n/ui_copy.dart'
if '--check' in sys.argv:
 if target.read_text()!=source:sys.exit('Regenerate UI copy with python3 tool/generate_ui_copy.py')
else:target.write_text(source)
