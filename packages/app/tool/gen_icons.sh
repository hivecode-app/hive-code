{
  echo "// GENERATED by tool/gen_icons.sh. Material Symbols Rounded (APP-SPEC §7.6), by name."
  echo "// Const entries keep icon tree-shaking working. Add a name to the script, then rerun it."
  echo "import 'package:flutter/widgets.dart';"
  echo "import 'package:material_symbols_icons/symbols.dart';"
  echo
