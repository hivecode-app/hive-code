// App icon: the Hive Code logo, "אות בתוך תא". The letter H cut out of one hexagonal cell.
//
// One geometry, every output: the Android adaptive icon (vector foreground and monochrome, light and
// night colors), legacy launcher PNGs, and the web favicon / apple-touch-icon / manifest icons.
// The brand files in docs/brand/hive-code/ are drawn from the same geometry (make_brand.mjs there).
//
// Usage: node packages/app/tool/make_icons.mjs [check.png]
// Needs sharp, which is already a dependency of the repo (npm ci at the root).
// The optional path writes a check sheet: home screen at 48 and 32, themed, and favicons in tabs.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const RES = path.join(ROOT, 'android', 'app', 'src', 'main', 'res');
const WEB = path.join(ROOT, 'web');

// ---------- geometry, in a 100x100 box ----------
// A pointy-top hexagon (circumradius R) with a slot from the top and a slot from the bottom; what is
// left is an H. The outline is drawn with a round-join stroke of the same color, which rounds the
// corners. The stroke also eats into the slots, so they are cut STROKE wider than they look.
export const R = 42;
export const STROKE = 5;
const SLOT = 18;        // visible slot width
const BAR = 20;         // visible crossbar height, centered
export const BLUE = '#1F6FEB';
export const BLUE_DARK = '#7AAEFF';

const r3 = (n) => +n.toFixed(3);
export function outline() {
  const s3 = Math.sqrt(3);
  const hx = (R * s3) / 2;                     // half width
  const L = 50 - hx, Rt = 50 + hx;             // left and right sides
  const xa = 50 - (SLOT + STROKE) / 2, xb = 50 + (SLOT + STROKE) / 2;
  const top = (x) => 50 - R + Math.abs(x - 50) / s3;   // y on the top edges
  const bot = (x) => 50 + R - Math.abs(x - 50) / s3;   // y on the bottom edges
  const yTop = 50 - BAR / 2 - STROKE / 2, yBot = 50 + BAR / 2 + STROKE / 2;
  return [
    [xa, top(xa)], [xa, yTop], [xb, yTop], [xb, top(xb)],
    [Rt, 50 - R / 2], [Rt, 50 + R / 2],
    [xb, bot(xb)], [xb, yBot], [xa, yBot], [xa, bot(xa)],
    [L, 50 + R / 2], [L, 50 - R / 2],
  ].map(([x, y]) => [r3(x), r3(y)]);
}
export const pathData = () => 'M' + outline().map((p) => p.join(',')).join(' L') + ' Z';
// Outer extent of the mark in the box, stroke included (for tight crops).
export const EXTENT = { half: R + STROKE / 2 };

/** The mark as SVG elements in the 100 box. */
export const markSvg = (fill) =>
  `<path d="${pathData()}" fill="${fill}" stroke="${fill}" stroke-width="${STROKE}" stroke-linejoin="round"/>`;

/** An SVG document: `box` units of the 100 box shown around the center, on an optional tile. */
function doc(size, { fg, bg = null, box = 100, shape = 'square' }) {
  const o = 50 - box / 2;
  let tile = '';
  if (bg) {
    if (shape === 'circle') tile = `<circle cx="50" cy="50" r="${box / 2}" fill="${bg}"/>`;
    else if (shape === 'rounded') tile = `<rect x="${o}" y="${o}" width="${box}" height="${box}" rx="${box * 0.22}" fill="${bg}"/>`;
    else tile = `<rect x="${o}" y="${o}" width="${box}" height="${box}" fill="${bg}"/>`;
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="${o} ${o} ${box} ${box}">${tile}${markSvg(fg)}</svg>`;
}
export const render = (size, opts) => sharp(Buffer.from(doc(size, opts)), { density: 72 * 4 }).resize(size, size).png();

// On a launcher tile the hexagon is about 62% of the tile: the 100 box spans 1/0.7 of it.
const TILE_BOX = 100 / 0.7;
// Tight around the mark, with a hair of air (favicon).
const TIGHT_BOX = 2 * EXTENT.half + 2;

// ---------- android ----------
// The adaptive canvas is 108dp; launchers show about the middle 72 and keep a 66 safe circle.
// The 100 box is drawn 72 * 0.7 = 50.4dp wide, the same proportion as TILE_BOX on the visible part.
const A_SCALE = (72 * 0.7) / 100;
const A_OFF = r3(54 - 50 * A_SCALE);

function vector(color) {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tool/make_icons.mjs: the Hive Code logo. Edit the script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group android:translateX="${A_OFF}" android:translateY="${A_OFF}" android:scaleX="${r3(A_SCALE)}" android:scaleY="${r3(A_SCALE)}">
        <path
            android:pathData="${pathData()}"
            android:fillColor="${color}"
            android:strokeColor="${color}"
            android:strokeWidth="${STROKE}"
            android:strokeLineJoin="round" />
    </group>
</vector>
`;
}

async function android() {
  const drawable = path.join(RES, 'drawable');
  fs.writeFileSync(path.join(drawable, 'ic_launcher_foreground.xml'), vector('@color/ic_launcher_foreground'));
  // Themed icons (Android 13+): the system tints this layer, so its color does not matter.
  fs.writeFileSync(path.join(drawable, 'ic_launcher_monochrome.xml'), vector('#FF000000'));
  // Legacy launcher PNGs (pre-adaptive launchers and tools that read mipmaps directly).
  for (const [name, px] of Object.entries({ mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 })) {
    await render(px, { fg: '#FFFFFF', bg: BLUE, box: TILE_BOX, shape: 'circle' }).toFile(path.join(RES, `mipmap-${name}`, 'ic_launcher.png'));
  }
}

// ---------- web ----------
function faviconSvg() {
  const o = r3(50 - TIGHT_BOX / 2);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${o} ${o} ${TIGHT_BOX} ${TIGHT_BOX}">
<style>path{color:${BLUE}}@media (prefers-color-scheme:dark){path{color:${BLUE_DARK}}}</style>
<path d="${pathData()}" fill="currentColor" stroke="currentColor" stroke-width="${STROKE}" stroke-linejoin="round"/>
</svg>
`;
}

/** An .ico with PNG entries (every current browser reads them). */
function ico(pngs) {
  const head = Buffer.alloc(6 + 16 * pngs.length);
  head.writeUInt16LE(0, 0); head.writeUInt16LE(1, 2); head.writeUInt16LE(pngs.length, 4);
  let offset = head.length;
  pngs.forEach(({ size, data }, i) => {
    const e = 6 + 16 * i;
    head.writeUInt8(size >= 256 ? 0 : size, e); head.writeUInt8(size >= 256 ? 0 : size, e + 1);
    head.writeUInt16LE(1, e + 4); head.writeUInt16LE(32, e + 6);
    head.writeUInt32LE(data.length, e + 8); head.writeUInt32LE(offset, e + 12);
    offset += data.length;
  });
  return Buffer.concat([head, ...pngs.map((p) => p.data)]);
}

async function web() {
  fs.writeFileSync(path.join(WEB, 'favicon.svg'), faviconSvg());
  const pngs = [];
  for (const size of [16, 32, 48]) pngs.push({ size, data: await render(size, { fg: BLUE, box: TIGHT_BOX }).toBuffer() });
  fs.writeFileSync(path.join(WEB, 'favicon.ico'), ico(pngs));
  // iOS draws its own rounded corners and wants an opaque square.
  await render(180, { fg: '#FFFFFF', bg: BLUE, box: TILE_BOX }).flatten({ background: BLUE }).toFile(path.join(WEB, 'apple-touch-icon.png'));
  for (const s of [192, 512]) {
    await render(s, { fg: '#FFFFFF', bg: BLUE, box: TILE_BOX, shape: 'rounded' }).toFile(path.join(WEB, 'icons', `Icon-${s}.png`));
    // Maskable: full bleed, the mark well inside the 80% safe circle.
    await render(s, { fg: '#FFFFFF', bg: BLUE, box: TILE_BOX * 1.1 }).toFile(path.join(WEB, 'icons', `Icon-maskable-${s}.png`));
  }
}

// ---------- check sheet ----------
async function check(out) {
  const W = 640, H = 300;
  const parts = [];
  const put = async (size, opts, left, top) => parts.push({ input: await render(size, opts).toBuffer(), left, top });
  const rows = [['#E8E8E4', '#D3D3CE', ['#1D3A6E', '#D6E2FA']], ['#212225', '#5A5C60', ['#D6E2FA', '#2A3550']]];
  let bg = '';
  for (const [i, [wall, other, mono]] of rows.entries()) {
    const y = 20 + i * 90;
    bg += `<rect x="10" y="${y}" width="620" height="80" fill="${wall}"/>`;
    let x = 24;
    for (const s of [48, 32]) {
      for (let k = 0; k < 3; k++) { bg += `<circle cx="${x + s / 2}" cy="${y + 40}" r="${s / 2}" fill="${other}"/>`; x += s + 14; }
      await put(s, { fg: '#FFFFFF', bg: BLUE, box: TILE_BOX, shape: 'circle' }, x, y + 40 - s / 2); x += s + 30;
    }
    for (const s of [48, 32]) { await put(s, { fg: mono[0], bg: mono[1], box: TILE_BOX, shape: 'circle' }, x, y + 40 - s / 2); x += s + 14; }
  }
  let x = 24;
  const y = 200;
  for (const [wall, fg] of [['#FFFFFF', BLUE], ['#35363A', BLUE_DARK]]) {
    bg += `<rect x="${x - 6}" y="${y + 22}" width="136" height="54" fill="${wall}"/>`;
    let xx = x;
    for (const s of [16, 32, 48]) { await put(s, { fg, box: TIGHT_BOX }, xx, y + 49 - s / 2); xx += s + 10; }
    x += 150;
  }
  const base = sharp(Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}"><rect width="100%" height="100%" fill="#F5F5F3"/>${bg}</svg>`));
  const sheet = await base.composite(parts).png().toBuffer();
  await sharp(sheet).resize(W * 3, H * 3, { kernel: 'nearest' }).toFile(out);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await android();
  await web();
  if (process.argv[2]) await check(process.argv[2]);
}
